#!/usr/bin/env python3
"""Cache the public universe's CC0 coin icons. No exchange/source writes."""
import argparse
import json
import re
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
# Pin all assets and license to the same upstream revision.
BASE = 'https://raw.githubusercontent.com/spothq/cryptocurrency-icons/1a63530be6e374711a8554f31b17e4cb92c25fa5'

def universe(path):
    data = json.loads(path.read_text())
    symbols = set()
    def walk(value):
        if isinstance(value, dict):
            for key, item in value.items():
                walk(key)
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
        elif isinstance(value, str) and re.fullmatch(r'[A-Z0-9]+-USDT-SWAP', value):
            symbols.add(value.split('-')[0].lower())
    walk(data)
    symbols.update(s.lower() for s in data.get('symbols', []) if re.fullmatch(r'[A-Z0-9]+', s))
    return symbols

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--universe', type=Path, default=ROOT/'paper/scan.json')
    args = parser.parse_args()
    target = ROOT/'assets/coins'
    target.mkdir(exist_ok=True)
    # Include publicly displayed holdings/fills and basic market coins even when paused scan is empty.
    symbols = universe(args.universe) | universe(ROOT/'paper/account.json') | {'btc', 'eth', 'sol', 'zec'}
    def fetch(symbol):
        dest = target/f'{symbol}.svg'
        if dest.exists():
            return symbol
        try:
            with urlopen(f'{BASE}/svg/color/{symbol}.svg', timeout=20) as response:
                body = response.read()
            if b'<svg' not in body or b'<script' in body:
                raise ValueError(f'Invalid SVG: {symbol}')
            dest.write_bytes(body)
            return symbol
        except HTTPError as error:
            if error.code != 404:
                raise
            return None  # Noncrypto contracts use deterministic initials in the UI.
    with ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(fetch, sorted(symbols)))
    license_path = target/'LICENSE.md'
    if not license_path.exists():
        with urlopen(f'{BASE}/LICENSE.md', timeout=20) as response:
            license_path.write_bytes(response.read())
    cached = sorted(p.stem for p in target.glob('*.svg'))
    (target/'manifest.mjs').write_text('// Generated by tools/fetch_icons.py; local assets only.\nexport const coinIcons = new Set('+json.dumps(cached)+');\n')
    print(f'{len(cached)} cached; {len(symbols)-len([r for r in results if r])} use initials')

if __name__ == '__main__':
    main()
